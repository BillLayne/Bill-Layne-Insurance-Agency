#!/usr/bin/env python3
"""
build-nav.py - keep every page's site menu identical to the homepage.

Source of truth:  tools/nav.json
Styles (standalone mode only): css/bli-nav.css

Two modes, chosen per wave in nav.json:

  standalone  For pages with NO site menu. Injects a self-contained footer nav
              + mobile dock between
                  <!-- BLI-NAV:START ... -->   ...   <!-- BLI-NAV:END -->
              plus one marked <link> in <head>. Re-runs replace in place.

  families    For pages that already carry one of the site's menu containers.
              Only the LINK ITEMS inside each container are re-rendered, in
              canonical order, using that family's own item markup; the
              wrapper, its classes, header and CTA are untouched. Families:
                #mobileDockPanel / #menuPanel  -> <ul class="menu-links">
                #menu-drawer                   -> <div class="... overflow-y-auto ...">
                #navigation-menu               -> <nav class="space-y-4">
                #mobile-menu                   -> <nav class="navbar-menu-nav">
              A container whose list cannot be located is reported and the
              page is left untouched.

Usage
    python tools/build-nav.py --wave 1              # dry run, summary
    python tools/build-nav.py --wave 2 --diff       # dry run with unified diffs
    python tools/build-nav.py --wave 2 --apply      # write
    python tools/build-nav.py --wave 2 --pages a.html b.html --apply
    python tools/build-nav.py --wave 2 --check      # exit 1 if anything is out of date

Every substitution asserts it matched exactly once; on any mismatch the file is
left untouched and reported as FAILED. This repo is the live site - read the
diff before you --apply.
"""

